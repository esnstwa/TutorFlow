const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const calls = [];
const window = {location: {href: 'https://example.com/students', origin: 'https://example.com'}, fetch: (input, options) => { calls.push({input, options}); return Promise.resolve({ok: true}); }};
const document = {querySelector: selector => selector === 'meta[name="csrf-token"]' ? {content: 'test-csrf'} : null};
const context = vm.createContext({window, document, URL, Request, Headers, Set});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../app/web/static/js/session.js'), 'utf8'), context);
(async () => {
  await window.fetch('/api/students');
  assert.equal(calls.at(-1).options.headers, undefined, 'GET must not receive CSRF header');
  await window.fetch('/api/students', {method: 'POST', body: '{}'});
  assert.equal(calls.at(-1).options.headers.get('X-CSRF-Token'), 'test-csrf');
  assert.equal(calls.at(-1).options.body, '{}');
  await window.fetch('https://other.example/collect', {method: 'POST'});
  assert.equal(calls.at(-1).options.headers, undefined, 'CSRF must never leave own origin');
  const request = new Request('https://example.com/api/students/1', {method: 'PATCH', headers: {'Content-Type': 'application/json'}, body: '{}'});
  await window.fetch(request);
  assert.equal(calls.at(-1).input, request);
  assert.equal(calls.at(-1).options.headers.get('Content-Type'), 'application/json');
  assert.equal(calls.at(-1).options.headers.get('X-CSRF-Token'), 'test-csrf');
  await window.fetch('/api/students', {method: 'DELETE', headers: {'X-CSRF-Token': 'stale'}});
  assert.equal(calls.at(-1).options.headers.get('X-CSRF-Token'), 'test-csrf');
  vm.runInContext(fs.readFileSync(path.join(__dirname, '../app/web/static/js/session.js'), 'utf8'), context);
  await window.fetch('/api/students', {method: 'POST'});
  assert.equal(calls.length, 6, 'navigation/reload must not wrap fetch twice');
  console.log('6 session fetch checks passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
